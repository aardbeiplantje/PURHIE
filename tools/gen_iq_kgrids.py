#!/usr/bin/env python3
# gen_iq_kgrids.py -- extract the base grids of ggml's IQ2 / IQ3 / IQ1 encoders (the tables quantize_iq2xs_init and
# iq3xs_init build their lookup tables from) into src/iq_kgrids.h
#
#   gen_iq_kgrids.py <ggml-quants.c> > src/iq_kgrids.h
#
# Copied verbatim from ggml (MIT License, Copyright (c) 2023-2026 The ggml authors).

import re, sys

# (function-local name, the name in the header, the element count)
NAMES = [("kgrid_2bit_256", "kgrid_2bit_256", 256), ("kgrid_2bit_512", "kgrid_2bit_512", 512),
         ("kgrid_1bit_2048", "kgrid_1bit_2048", 2048), ("kgrid_2bit_1024", "kgrid_2bit_1024", 1024),
         ("kgrid_256", "kgrid_iq3_256", 256), ("kgrid_512", "kgrid_iq3_512", 512)]


def main():
    src = open(sys.argv[1]).read()
    out = ["// iq_kgrids.h -- generated by tools/gen_iq_kgrids.py from ggml's ggml-quants.c: do not edit.",
           "// The base grids of the IQ2 / IQ3 / IQ1 encoders (ggml's iq2xs_init and iq3xs_init), copied verbatim from ggml",
           "// (MIT License, Copyright (c) 2023-2026 The ggml authors).",
           "#pragma once", "#include <stdint.h>", ""]
    for name, out_name, n in NAMES:
        m = re.search(r"static const uint16_t " + name + r"\[[^\]]*\] = \{\n(.*?)\n\s*\};", src, re.S)
        if not m:
            sys.exit(f"{name}: not found")
        body = m.group(1).rstrip()
        out.append(f"static const uint16_t {out_name}[{n}] = {{")
        out.append(body)
        out.append("};")
        out.append("")
    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    main()
