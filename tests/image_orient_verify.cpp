// the TIFF structure of an Exif block: a Make entry (to step over), then the orientation (a SHORT; type 4, a LONG, to test a
// malformed one)
static Bytes tiff(int orientation, bool le, int type = 3) {
    Bytes t;
    auto u16 = [&](uint32_t v) {
        if (le) t.insert(t.end(), {(unsigned char)v, (unsigned char)(v >> 8)});
        else t.insert(t.end(), {(unsigned char)(v >> 8), (unsigned char)v});
    };
    auto u32 = [&](uint32_t v) {
        if (le) t.insert(t.end(), {(unsigned char)v, (unsigned char)(v >> 8), (unsigned char)(v >> 16), (unsigned char)(v >> 24)});
        else t.insert(t.end(), {(unsigned char)(v >> 24), (unsigned char)(v >> 16), (unsigned char)(v >> 8), (unsigned char)v});
    };
    t.insert(t.end(), le ? std::initializer_list<unsigned char>{'I', 'I'} : std::initializer_list<unsigned char>{'M', 'M'});
    u16(42);
    u32(8);
    u16(2);  // two entries
    u16(0x010F);  // Make: ASCII, 4 bytes in place
    u16(2);
    u32(4);
    t.insert(t.end(), {'a', 'b', 'c', 0});
    u16(0x0112);  // Orientation
    u16((uint32_t)type);
    u32(1);
    u16((uint32_t)orientation);
    u16(0);
    u32(0);  // no next directory
    return t;
}

static Bytes segment(unsigned char marker, const Bytes& body) {
    Bytes s = {0xFF, marker, (unsigned char)((body.size() + 2) >> 8), (unsigned char)(body.size() + 2)};
    s.insert(s.end(), body.begin(), body.end());
    return s;
}

// the JPEG with segments after its SOI
static Bytes jpeg_with(const std::vector<Bytes>& segs) {
    Bytes j(kJpeg, kJpeg + 2);
    for (const Bytes& s : segs) j.insert(j.end(), s.begin(), s.end());
    j.insert(j.end(), kJpeg + 2, kJpeg + sizeof kJpeg);
    return j;
}

static Bytes exif_app1(const Bytes& t) {
    Bytes b = {'E', 'x', 'i', 'f', 0, 0};
    b.insert(b.end(), t.begin(), t.end());
    return segment(0xE1, b);
}

static Bytes xmp_app1() {
    const std::string s = std::string("http://ns.adobe.com/xap/1.0/") + '\0' + "<x:xmpmeta/>";
    return segment(0xE1, Bytes(s.begin(), s.end()));
}

static void png_chunk(Bytes& p, const char* type, const Bytes& data) {
    const uint32_t n = (uint32_t)data.size();
    p.insert(p.end(), {(unsigned char)(n >> 24), (unsigned char)(n >> 16), (unsigned char)(n >> 8), (unsigned char)n});
    const size_t at = p.size();
    p.insert(p.end(), type, type + 4);
    p.insert(p.end(), data.begin(), data.end());
    const uint32_t c = (uint32_t)crc32(0, p.data() + at, (uInt)(4 + n));
    p.insert(p.end(), {(unsigned char)(c >> 24), (unsigned char)(c >> 16), (unsigned char)(c >> 8), (unsigned char)c});
}

// an RGBA PNG of w x h (px row-major), with an eXIf chunk when exif is not empty
static Bytes png_rgba(const Bytes& px, int w, int h, const Bytes& exif) {
    Bytes p = {0x89, 'P', 'N', 'G', '\r', '\n', 0x1a, '\n'};
    Bytes ihdr = {(unsigned char)(w >> 24), (unsigned char)(w >> 16), (unsigned char)(w >> 8), (unsigned char)w,
                  (unsigned char)(h >> 24), (unsigned char)(h >> 16), (unsigned char)(h >> 8), (unsigned char)h, 8, 6, 0, 0, 0};
    png_chunk(p, "IHDR", ihdr);
    if (!exif.empty()) png_chunk(p, "eXIf", exif);
    Bytes raw;
    for (int y = 0; y < h; ++y) {
        raw.push_back(0);
        raw.insert(raw.end(), px.begin() + (size_t)y * w * 4, px.begin() + (size_t)(y + 1) * w * 4);
    }
    uLongf zn = compressBound((uLong)raw.size());
    Bytes z(zn);
    compress2(z.data(), &zn, raw.data(), (uLong)raw.size(), 6);
    z.resize(zn);
    png_chunk(p, "IDAT", z);
    png_chunk(p, "IEND", {});
    return p;
}

// where the stored pixel (r, c) of a w x h image is shown, by the EXIF definition: the side the first row is at, the side the
// first column is at
static void shown_at(int o, int w, int h, int r, int c, int* x, int* y, int* ow, int* oh) {
    enum { TOP, BOTTOM, LEFT, RIGHT };
    static const int row0[9] = {0, TOP, TOP, BOTTOM, BOTTOM, LEFT, RIGHT, RIGHT, LEFT};
    static const int col0[9] = {0, LEFT, RIGHT, RIGHT, LEFT, TOP, TOP, BOTTOM, BOTTOM};
    if (row0[o] == TOP || row0[o] == BOTTOM) {
        *y = row0[o] == TOP ? r : h - 1 - r;
        *x = col0[o] == LEFT ? c : w - 1 - c;
        *ow = w;
        *oh = h;
    } else {
        *x = row0[o] == LEFT ? r : h - 1 - r;
        *y = col0[o] == TOP ? c : w - 1 - c;
        *ow = h;
        *oh = w;
    }
}

static int g_fail = 0;

// the decode of img (ch 3: rgb, 4: rgba) against the stored pixels placed for orientation o
static void check(const char* name, const Bytes& img, int ch, const unsigned char* stored, int w, int h, int o) {
    unsigned char* px = nullptr;
    int dw = 0, dh = 0, alpha = -1;
    const int rc = ch == 3 ? image_decode_rgb(img.data(), img.size(), &px, &dw, &dh)
                           : image_decode_rgba(img.data(), img.size(), &px, &dw, &dh, &alpha);
    if (rc != 0) {
        std::printf("  %-34s FAIL: no decode\n", name);
        ++g_fail;
        return;
    }
    int x = 0, y = 0, ow = 0, oh = 0;
    shown_at(o, w, h, 0, 0, &x, &y, &ow, &oh);
    long bad = 0;
    if (dw != ow || dh != oh) {
        bad = -1;
    } else {
        for (int r = 0; r < h; ++r)
            for (int c = 0; c < w; ++c) {
                shown_at(o, w, h, r, c, &x, &y, &ow, &oh);
                if (std::memcmp(px + ((size_t)y * dw + x) * ch, stored + ((size_t)r * w + c) * ch, (size_t)ch) != 0) ++bad;
            }
    }
    const bool ok = bad == 0 && (ch == 3 || alpha == 1 || name[0] != 'p');
    std::printf("  %-34s %d x %d  %s\n", name, dw, dh, ok ? "ok" : bad < 0 ? "FAIL: size" : "FAIL: pixels");
    if (!ok) ++g_fail;
    image_free(px);
}

int main(int argc, char** argv) {
    if (argc == 3) {  // a file's decode as PPM
        std::ifstream f(argv[1], std::ios::binary);
        const Bytes d((std::istreambuf_iterator<char>(f)), std::istreambuf_iterator<char>());
        unsigned char* px = nullptr;
        int w = 0, h = 0;
        if (d.empty() || image_decode_rgb(d.data(), d.size(), &px, &w, &h) != 0) {
            std::fprintf(stderr, "cannot decode %s\n", argv[1]);
            return 1;
        }
        FILE* o = std::fopen(argv[2], "wb");
        std::fprintf(o, "P6\n%d %d\n255\n", w, h);
        std::fwrite(px, 1, (size_t)w * h * 3, o);
        std::fclose(o);
        image_free(px);
        std::printf("%d %d\n", w, h);
        return 0;
    }
    // the stored pixels: the JPEG without any Exif
    const Bytes plain(kJpeg, kJpeg + sizeof kJpeg);
    unsigned char *s3 = nullptr, *s4 = nullptr;
    int w = 0, h = 0, w4 = 0, h4 = 0, a = 0;
    if (image_decode_rgb(plain.data(), plain.size(), &s3, &w, &h) != 0 ||
        image_decode_rgba(plain.data(), plain.size(), &s4, &w4, &h4, &a) != 0) {
        std::printf("FAIL: the embedded JPEG does not decode\n");
        return 1;
    }
    std::printf("the JPEG: %d x %d\n", w, h);
    for (int o = 1; o <= 8; ++o)
        for (int le = 0; le < 2; ++le) {
            const Bytes j = jpeg_with({xmp_app1(), exif_app1(tiff(o, le != 0))});
            char name[64];
            std::snprintf(name, sizeof name, "jpeg %d %s rgb", o, le ? "II" : "MM");
            check(name, j, 3, s3, w, h, o);
            std::snprintf(name, sizeof name, "jpeg %d %s rgba", o, le ? "II" : "MM");
            check(name, j, 4, s4, w, h, o);
        }
    // what cannot be read: as stored
    check("jpeg orientation 9", jpeg_with({exif_app1(tiff(9, true))}), 3, s3, w, h, 1);
    check("jpeg orientation as a LONG", jpeg_with({exif_app1(tiff(6, true, 4))}), 3, s3, w, h, 1);
    {
        Bytes t = tiff(6, false);
        t.resize(16);  // cut inside the directory
        check("jpeg Exif cut short", jpeg_with({exif_app1(t)}), 3, s3, w, h, 1);
        Bytes bad = tiff(6, true);
        bad[2] = 41;  // not TIFF's 42
        check("jpeg not TIFF", jpeg_with({exif_app1(bad)}), 3, s3, w, h, 1);
    }
    // a PNG with alpha: as stored, and turned (eXIf, big-endian, orientation 6)
    const int pw = 7, ph = 5;
    Bytes px((size_t)pw * ph * 4);
    for (int i = 0; i < pw * ph; ++i) {
        px[i * 4] = (unsigned char)(i * 7);
        px[i * 4 + 1] = (unsigned char)(255 - i * 5);
        px[i * 4 + 2] = (unsigned char)(i * 3 + 1);
        px[i * 4 + 3] = (unsigned char)(i % 2 ? 255 : i * 6);
    }
    check("png rgba, no eXIf", png_rgba(px, pw, ph, {}), 4, px.data(), pw, ph, 1);
    check("png rgba, eXIf 6", png_rgba(px, pw, ph, tiff(6, false)), 4, px.data(), pw, ph, 6);
    check("png rgba, eXIf 3", png_rgba(px, pw, ph, tiff(3, true)), 4, px.data(), pw, ph, 3);
    image_free(s3);
    image_free(s4);
    std::printf("%s\n", g_fail ? "FAIL" : "PASS");
    return g_fail ? 1 : 0;
}
